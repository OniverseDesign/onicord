export function buildCombinedV2Configs(pluginWidgets = []) {
  const pluginConfigs = (pluginWidgets || []).map((pw) => ({
    id: pw.fullId,
    title: pw.title || pw.badgeText || "Addon",
    description: pw.description || "Widget de complemento",
    icon: "extension",
    defaultSurface: pw.bgVariant || "dark",
    defaultGeo: pw.defaultGeo || { x: 1, y: 1, w: 3, h: 3 },
    minW: pw.minW || 2,
    minH: pw.minH || 2,
    maxW: pw.maxW || 12,
    maxH: pw.maxH || 8,
    isV2Native: false,
    isPlugin: true,
    pluginMeta: pw,
    component: PluginWidgetAdapterV2,
  }));

  return [...V2_WIDGET_REGISTRY, ...pluginConfigs];
}
